import { dialog } from './dialog.ts';
import { el } from './dom.ts';

const LINES: [string, string][] = [
  ['一回合', '大家同时选挡出牌（暗选）；然后从最前面的车起，一辆一辆亮牌、移动、反应、吸尾流、过弯、弃牌、补到 7 张。'],
  ['换挡', '升降 1 挡免费，升降 2 挡付 1 张热量。挂几挡出几张牌。'],
  ['速度', '牌面加起来就是速度，正好走这么多格。路过别的车不受阻；停的格内线有车停外线，都满了往后找。'],
  ['手抖', '打出去时从牌堆往下翻，翻到 1–4 的速度牌为止，算它的点数（改装牌 0、5 翻到不算）。'],
  ['热量', '打不出去、弃不掉。过弯超速、跳两挡、冲刺都从引擎里付热量。'],
  ['散热', '1 挡散 3 张、2 挡散 1 张：手里的热量放回引擎（自动做满）。'],
  ['冲刺', '任何挡都能，付 1 张热量，翻一张速度牌加到速度上，每回合一次。'],
  ['拼劲', '这回合最后走的车（5 辆车以上是最后两辆）：多走 1 格（速度 +1）、多散热 1 张。'],
  ['尾流', '停在别人旁边或正后方一格，可以再走 2 格；不算速度，不能靠它冲线。'],
  ['过弯', '跨过弯道线时速度超过限速几格，就付几张热量；付不起就打滑：退回弯前、挂回 1 挡、拿手抖牌（1–2 挡 1 张，3–4 挡 2 张）。'],
  ['熄火', '手里能打的牌不够这一挡：车不动，挂回 1 挡。'],
  ['冲线', '跑完圈数先过线的赢；同一回合过线的，过线越远越前，同一格内线在前。'],
];

export function showRules(stage: HTMLElement): void {
  dialog(stage, 'rules', (box) => {
    el('h2', '', box, '规则速查');
    const dl = el('dl', 'rules-list', box);
    for (const [k, v] of LINES) {
      el('dt', '', dl, k);
      el('dd', '', dl, v);
    }
  });
}
